namespace Piper.Syntax;

public enum TokenKind
{
    EndOfFile,
    BadToken,

    // Literals and names
    Identifier,
    IntegerLiteral,
    DoubleLiteral,
    /// <summary><c>30s</c>, <c>500ms</c>, <c>5min</c>, <c>2h</c>, <c>1day</c>: its <see cref="Token.Value"/> is a <see cref="System.TimeSpan"/>.</summary>
    DurationLiteral,
    CharLiteral,
    StringLiteral,
    InterpolatedStringLiteral,
    /// <summary><c>&lt;p&gt;Hello, {name}&lt;/p&gt;</c>: its <see cref="Token.Value"/> is a <see cref="MarkupElement"/>.</summary>
    MarkupLiteral,

    // Keywords
    FnKeyword,
    LetKeyword,
    MutKeyword,
    IfKeyword,
    ElseKeyword,
    WhileKeyword,
    ForKeyword,
    InKeyword,
    ReturnKeyword,
    BreakKeyword,
    ContinueKeyword,
    RecordKeyword,
    EnumKeyword,
    MatchKeyword,
    TraitKeyword,
    ExtendKeyword,
    ThisKeyword,
    StaticKeyword,
    NullKeyword,
    IsKeyword,
    NamespaceKeyword,
    UsingKeyword,
    PrivateKeyword,
    TryKeyword,
    CatchKeyword,
    FinallyKeyword,
    DeferKeyword,
    ThrowKeyword,
    OutKeyword,
    /// <summary>A builtin type name: int, string, … (the token's text says which).</summary>
    PredefinedTypeKeyword,
    TrueKeyword,
    FalseKeyword,

    // Punctuation
    OpenParen,
    CloseParen,
    OpenBrace,
    CloseBrace,
    OpenBracket,
    CloseBracket,
    Comma,
    Semicolon,
    Colon,
    Dot,
    DotDot,
    DotDotLess,
    /// <summary>`^`: an index from the end, as in `xs[^1]`, or exclusive or, as in `a ^ b`.</summary>
    Caret,
    /// <summary>`...`: a spread, as in `{ ...p, y: 5 }`.</summary>
    Ellipsis,
    Arrow,
    FatArrow,
    Question,
    QuestionQuestion,
    QuestionDot,

    // Operators
    Equals,
    EqualsEquals,
    Bang,
    BangEquals,
    Less,
    LessEquals,
    Greater,
    GreaterEquals,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    AmpersandAmpersand,
    Ampersand,
    Tilde,
    LessLess,
    /// <summary>`>>`: never lexed, since `List<List<int>>` ends in two `>`s; the parser joins two adjacent ones.</summary>
    GreaterGreater,
    PipePipe,
    PipeGreater,
    Pipe,
    PlusEquals,
    MinusEquals,
    StarEquals,
    SlashEquals,
    PercentEquals,
    AmpersandEquals,
    PipeEquals,
    CaretEquals,
    LessLessEquals,
    /// <summary>`>>=`: never lexed, but joined by the parser from `>` and `>=`, as <see cref="GreaterGreater"/> is.</summary>
    GreaterGreaterEquals,
    QuestionQuestionEquals,
}

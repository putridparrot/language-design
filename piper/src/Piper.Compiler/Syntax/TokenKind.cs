    BadToken,

    // Literals and names
    Identifier,
    IntegerLiteral,
    DoubleLiteral,
    CharLiteral,
    StringLiteral,
    InterpolatedStringLiteral,

    // Keywords
    FnKeyword,
    LetKeyword,
    VarKeyword,
    IfKeyword,
    ElseKeyword,
    WhileKeyword,
    ForKeyword,
    InKeyword,
    ReturnKeyword,
    BreakKeyword,
    ContinueKeyword,
    RecordKeyword,
    EnumKeyword,
